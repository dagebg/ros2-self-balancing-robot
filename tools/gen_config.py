#!/usr/bin/env python3
"""Generate the firmware's robot_config.hpp from config/robot_params.yaml.

The YAML file is the single source of truth for robot constants. This script
turns it into C++17 ``inline constexpr`` values so the firmware never carries a
second, drifting copy.

Usage:
    python tools/gen_config.py            # write the header
    python tools/gen_config.py --check    # exit 1 if the header is stale
"""

from __future__ import annotations

import argparse
import sys
import textwrap
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
PARAMS_FILE = REPO_ROOT / "config" / "robot_params.yaml"
HEADER_FILE = REPO_ROOT / "firmware" / "esp32" / "robot-firmware" / "include" / "robot_config.hpp"

REQUIRED_KEYS = ("value", "unit", "measured", "doc")
COLUMN_LIMIT = 100  # matches .clang-format


def to_constant_name(name: str) -> str:
    """Map ``wheel_radius`` to ``kWheelRadius``. Names are unique across groups."""
    return "k" + "".join(part.capitalize() for part in name.split("_"))


def cpp_literal(value: object) -> tuple[str, str]:
    """Return the C++ type and literal for a YAML scalar."""
    if isinstance(value, bool):
        raise TypeError("boolean parameters are not supported")
    if isinstance(value, int):
        return "std::int32_t", str(value)
    if isinstance(value, float):
        return "float", f"{value!r}F"
    raise TypeError(f"unsupported parameter type: {type(value).__name__}")


def load_params(path: Path) -> dict[str, dict[str, dict]]:
    params = yaml.safe_load(path.read_text(encoding="utf-8"))
    seen: set[str] = set()
    for group, entries in params.items():
        for name, entry in entries.items():
            missing = [key for key in REQUIRED_KEYS if key not in entry]
            if missing:
                raise ValueError(f"{group}.{name}: missing keys {missing}")
            if name in seen:
                raise ValueError(f"duplicate parameter name: {name}")
            seen.add(name)
    return params


def render_header(params: dict[str, dict[str, dict]]) -> str:
    lines = [
        "// Generated by tools/gen_config.py from config/robot_params.yaml. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "/// Robot constants shared with the ROS 2 packages and the simulation.",
        "namespace robot::config {",
    ]
    all_measured = True
    for group, entries in params.items():
        lines += ["", f"// --- {group} " + "-" * (90 - len(group))]
        for name, entry in entries.items():
            cpp_type, literal = cpp_literal(entry["value"])
            status = "" if entry["measured"] else " PLACEHOLDER: not measured yet."
            all_measured &= bool(entry["measured"])
            doc = f"{entry['doc']} [{entry['unit']}]{status}"
            lines += textwrap.wrap(
                doc, COLUMN_LIMIT, initial_indent="/// ", subsequent_indent="/// "
            )
            lines.append(f"inline constexpr {cpp_type} {to_constant_name(name)} = {literal};")
    lines += [
        "",
        "/// False while any parameter above is still a placeholder.",
        f"inline constexpr bool kAllParamsMeasured = {'true' if all_measured else 'false'};",
        "",
        "}  // namespace robot::config",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the header is out of date")
    args = parser.parse_args(argv)

    header = render_header(load_params(PARAMS_FILE))
    if args.check:
        current = HEADER_FILE.read_text(encoding="utf-8") if HEADER_FILE.exists() else ""
        if current != header:
            print(f"{HEADER_FILE.relative_to(REPO_ROOT)} is out of date; run tools/gen_config.py")
            return 1
        return 0
    HEADER_FILE.write_text(header, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
